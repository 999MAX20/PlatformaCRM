import { test, expect } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { ru as t } from "../src/lib/i18n/ru";
import { requireIsolatedEnvironment } from "./isolated-environment.mjs";

requireIsolatedEnvironment();
test("template DOCX: saved version download retry and revoked access", async ({ page }, info) => {
  test.setTimeout(120_000);
  const marker = crypto.randomUUID();
  const title = `Synthetic DOCX template ${marker}`;
  const text = `Synthetic literal {{patient.full_name}} ${marker}`;
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.addInitScript(() => localStorage.setItem("ai_smb_language", "ru"));
  await page.goto("/login");
  await page.locator('input[name="email"]').fill("medical-template-head@example.test");
  await page.locator('input[name="password"]').fill(process.env.E2E_PASSWORD!);
  const auth = page.waitForResponse(response => response.url().endsWith("/api/auth/token/") && response.request().method() === "POST");
  await page.locator('form button[type="submit"]').click();
  const headers = { Authorization: `Bearer ${(await (await auth).json()).access}`, "Idempotency-Key": crypto.randomUUID() };
  await expect(page).toHaveURL(/\/app\//);
  const created = await page.request.post(`${process.env.E2E_API_BASE_URL}/api/medical/document-templates/common/`, {
    headers, data: { business_id: 1, title, text, reason: "" } });
  expect(created.ok(), await created.text()).toBe(true);
  const version = await created.json();
  const configured = await page.request.post(`${process.env.E2E_API_BASE_URL}/api/medical/document-kinds/`, {
    headers: { ...headers, "Idempotency-Key": crypto.randomUUID() }, data: { business_id: 1,
      template_ids: [version.id], reason: "Synthetic export opt-in", content: { name: title, docx_allowed: true,
        default: { required_at: "optional", required_fields: [], reviewers: ["primary_clinician"], signers: [], issuable: false }, services: [] } } });
  expect(configured.ok(), await configured.text()).toBe(true);
  await page.goto("/app/settings#medical-templates");
  const workspace = page.getByTestId("medical-template-workspace");
  await workspace.getByRole("button", { name: t["medical.templates.common"], exact: true }).click();
  await workspace.getByRole("textbox", { name: t["medical.templates.searchText"], exact: true }).fill(marker);
  await workspace.getByRole("button", { name: t["medical.templates.search"], exact: true }).click();
  const row = workspace.getByRole("listitem").filter({ hasText: title });
  const open = row.getByRole("button", { name: t["medical.templates.open"], exact: true });
  await open.click();
  const dialog = page.getByRole("dialog");
  const exportArea = dialog.getByTestId("template-docx");
  const download = exportArea.getByRole("button", { name: t["medical.templates.downloadDocx"], exact: true });
  await expect(download).toBeEnabled();
  await download.focus(); await expect(download).toBeFocused();
  await page.screenshot({ path: info.outputPath("template-docx-desktop.png") });
  const received = page.waitForEvent("download");
  await page.keyboard.press("Enter");
  const artifact = await received;
  const filename = info.outputPath("template-draft.docx");
  await artifact.saveAs(filename);
  execFileSync(process.env.E2E_PYTHON!, ["-c", "from docx import Document; import sys; d=Document(sys.argv[1]); assert sys.argv[2] in '\\n'.join(p.text for p in d.paragraphs); assert 'Черновик' in '\\n'.join(p.text for s in d.sections for p in s.header.paragraphs)", filename, text], { windowsHide: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(download).toBeEnabled();
  const url = `**/api/medical/document-templates/versions/${version.version_id}/docx-download/`;
  let fail = true;
  await page.route(url, route => fail ? (fail = false, route.fulfill({ status: 503, json: { detail: "Synthetic scanner outage" } })) : route.continue());
  await download.click();
  const retry = exportArea.getByRole("button", { name: t["common.retry"], exact: true });
  await expect(retry).toBeVisible();
  await expect(dialog.getByText(text, { exact: true })).toBeVisible();
  await retry.scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath("template-docx-mobile-retry.png") });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const repeated = page.waitForEvent("download");
  await retry.click(); await repeated;
  await expect(retry).toHaveCount(0);
  await expect(download).toBeEnabled();
  await page.unroute(url);
  await page.route(url, route => route.fulfill({ status: 409, json: { detail: "Synthetic rules changed during export" } }));
  await download.click();
  await expect(download).toHaveCount(0);
  await expect(retry).toBeVisible();
  await expect(dialog.getByText(text, { exact: true })).toBeVisible();
  await retry.evaluate(element => element.scrollIntoView({ block: "center", behavior: "instant" }));
  await page.screenshot({ path: info.outputPath("template-docx-conflict-mobile.png") });
  const reloaded = page.waitForResponse(response => response.url().includes(`/versions/${version.version_id}/docx-access/`) && response.request().method() === "GET");
  await retry.click();
  expect((await reloaded).ok()).toBe(true);
  await expect(download).toBeEnabled();
  await expect(retry).toHaveCount(0);
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await expect(open).toBeFocused();
  await open.click(); await expect(download).toBeEnabled();
  await page.unroute(url);
  await page.route(url, route => route.fulfill({ status: 403, json: { detail: "Synthetic revoked access" } }));
  await download.click();
  await expect(dialog).toHaveCount(0);
  await expect(workspace.getByText(title, { exact: true })).toHaveCount(0);
});
