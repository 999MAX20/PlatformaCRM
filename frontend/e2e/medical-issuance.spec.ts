requireIsolatedEnvironment();
test("personally hand code, activate, open exact PDF and revoke", async ({ page, browser }, info) => {
  const entry = JSON.parse(execFileSync(process.env.E2E_PYTHON!, ["e2e/clinical-runtime.py", "issuance-prepare"],
    { env: process.env, windowsHide: true, encoding: "utf8" }).trim().split(/\r?\n/).at(-1)!);
  await page.addInitScript(() => localStorage.setItem("ai_smb_language", "ru"));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/login");
  await page.locator('input[name="email"]').fill(entry.email);
  await page.locator('input[name="password"]').fill(process.env.E2E_PASSWORD!);
  await page.locator('form button[type="submit"]').click();
  await expect(page).toHaveURL(/\/app\//);
  await page.goto(`/app/clients/${entry.client_id}`);
  const administration = page.getByTestId("patient-administration");
  await administration.getByLabel(ru["medical.branch"], { exact: true }).click();
  await page.getByRole("option", { name: "Synthetic completion branch", exact: true }).click();
  await administration.getByRole("button", { name: ru["medical.issue.title"], exact: true }).click();
  const dialog = page.getByTestId("medical-document-issuance");
  await dialog.getByLabel(ru["medical.issue.encounter"], { exact: true }).click();
  await page.getByRole("option", { name: new RegExp(`№${entry.encounter_id} ·`) }).click();
  await dialog.getByRole("checkbox", { name: new RegExp(entry.title) }).check();
  await dialog.getByRole("checkbox", { name: ru["medical.issue.verified"], exact: true }).check();
  await dialog.getByRole("textbox", { name: ru["medical.issue.verification"], exact: true }).fill("Synthetic in-person recipient verification");
  await page.screenshot({ path: info.outputPath("issuance-desktop.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: info.outputPath("issuance-mobile.png") });
  await dialog.getByRole("button", { name: ru["medical.issue.create"], exact: true }).click();
  const code = await dialog.getByRole("textbox", { name: ru["medical.issue.code"], exact: true }).inputValue();
  expect(code).toHaveLength(20);
  const portalUrl = await dialog.getByRole("textbox", { name: ru["medical.issue.link"], exact: true }).inputValue();
  expect(portalUrl).not.toContain(code);
  await dialog.getByRole("button", { name: ru["medical.issue.dismiss"], exact: true }).click();
  const patientContext = await browser.newContext();
  const patient = await patientContext.newPage();
  await patient.addInitScript(() => localStorage.setItem("ai_smb_language", "ru"));
  await patient.goto(portalUrl);
  await patient.getByRole("textbox", { name: ru["medical.issue.code"], exact: true }).fill(code);
  await patient.getByRole("button", { name: ru["medical.issue.open"], exact: true }).click();
  await expect(patient.getByText(ru["medical.issue.unavailable"], { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: ru["medical.issue.activate"], exact: true }).click();
  await expect(dialog.getByText(ru["medical.issue.saved"], { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: ru["medical.issue.dismiss"], exact: true }).click();
  await patient.getByRole("button", { name: ru["medical.issue.open"], exact: true }).click();
  await expect(patient.getByRole("heading", { name: entry.title, exact: true })).toBeVisible();
  await patient.setViewportSize({ width: 1440, height: 900 });
  await patient.screenshot({ path: info.outputPath("portal-desktop.png") });
  await patient.setViewportSize({ width: 390, height: 844 });
  await patient.screenshot({ path: info.outputPath("portal-mobile.png") });
  const archiveButton=patient.getByRole("button",{name:ru["medical.issue.archive"],exact:true});
  await patient.route("**/api/medical/portal/*/archive/",route=>route.fulfill({status:503,json:{detail:"Synthetic archive unavailable"}}));
  await archiveButton.click();await expect(patient.getByRole("alert")).toContainText(ru["medical.issue.archiveUnavailable"]);await expect(patient.getByRole("heading",{name:entry.title,exact:true})).toBeVisible();
  await patient.unroute("**/api/medical/portal/*/archive/");
  const downloaded=patient.waitForEvent("download");await archiveButton.click();const archive=await downloaded;
  expect(archive.suggestedFilename()).toBe("documents.zip");const archivePath=await archive.path();
  const summary=JSON.parse(execFileSync(process.env.E2E_PYTHON!,["-c","import sys,zipfile,json; z=zipfile.ZipFile(sys.argv[1]); m=json.loads(z.read('manifest.json')); print(json.dumps({'kind':m['kind'],'count':len(m['documents']),'paths':z.namelist()}))",archivePath!],{windowsHide:true,encoding:"utf8"}));
  expect(summary.kind).toBe("issued-document-package");expect(summary.count).toBe(1);expect(summary.paths).toContain("index.html");
  const view = patient.getByRole("link", { name: ru["medical.issue.view"], exact: true });
  const file = (await view.getAttribute("href"))!;
  const pdf = await patient.evaluate(async url => { const response = await fetch(url, { credentials: "include" }); return { status: response.status, type: response.headers.get("content-type"), size: (await response.arrayBuffer()).byteLength }; }, file);
  expect(pdf.status).toBe(200); expect(pdf.type).toBe("application/pdf"); expect(pdf.size).toBeGreaterThan(100);
  await expect(view).toHaveAttribute("target", "_blank");
  const popupPromise = patient.waitForEvent("popup");
  const fileResponse = patientContext.waitForEvent("response", response => response.url() === new URL(file, portalUrl).href);
  await view.click();
  const popup = await popupPromise;
  expect((await fileResponse).status()).toBe(200);
  await popup.close();
  await dialog.getByRole("button", { name: ru["medical.issue.revoke"], exact: true }).click();
  await dialog.getByRole("textbox", { name: ru["medical.issue.reason"], exact: true }).fill("Synthetic lost code");
  await dialog.getByRole("button", { name: ru["medical.issue.revoke"], exact: true }).click();
  await expect(dialog.getByText(ru["medical.issue.saved"], { exact: true })).toBeVisible();
  await archiveButton.click();
  await expect(patient.getByRole("heading", { name: entry.title })).toHaveCount(0);
  expect(await patient.evaluate(async url => (await fetch(url, { credentials: "include" })).status, file)).toBe(403);
  await patientContext.close();
});

test("issuance KK retains input on failure and clears denied data", async ({ page }, info) => {
  const entry = JSON.parse(execFileSync(process.env.E2E_PYTHON!, ["e2e/clinical-runtime.py", "issuance-prepare"],
    { env: process.env, windowsHide: true, encoding: "utf8" }).trim().split(/\r?\n/).at(-1)!);
  await page.addInitScript(() => localStorage.setItem("ai_smb_language", "kk"));
  await page.goto("/login");
  await page.locator('input[name="email"]').fill(entry.email);
  await page.locator('input[name="password"]').fill(process.env.E2E_PASSWORD!);
  await page.locator('form button[type="submit"]').click();
  await expect(page).toHaveURL(/\/app\//);
  await page.goto(`/app/clients/${entry.client_id}`);
  const administration = page.getByTestId("patient-administration");
  await administration.getByLabel(kk["medical.branch"], { exact: true }).click();
  await page.getByRole("option", { name: "Synthetic completion branch", exact: true }).click();
  await administration.getByRole("button", { name: kk["medical.issue.title"], exact: true }).click();
  const dialog = page.getByTestId("medical-document-issuance");
  await dialog.getByLabel(kk["medical.issue.encounter"], { exact: true }).click();
  await page.getByRole("option", { name: new RegExp(`№${entry.encounter_id} ·`) }).click();
  await dialog.getByRole("checkbox", { name: new RegExp(entry.title) }).check();
  await dialog.getByRole("checkbox", { name: kk["medical.issue.verified"], exact: true }).check();
  const reason = dialog.getByRole("textbox", { name: kk["medical.issue.verification"], exact: true });
  await reason.fill("Retained recipient check");
  const save = dialog.getByRole("button", { name: kk["medical.issue.create"], exact: true });
  await page.route("**/api/medical/document-grants/", route => route.request().method() === "POST" ? route.fulfill({ status: 503, json: { detail: "Synthetic unavailable" } }) : route.continue());
  await save.click();
  await expect(dialog.getByRole("alert")).toBeVisible();
  await expect(reason).toHaveValue("Retained recipient check");
  await page.unroute("**/api/medical/document-grants/");
  await page.route("**/api/medical/document-grants/", route => route.request().method() === "POST" ? route.fulfill({ status: 409, json: { detail: "Synthetic conflict" } }) : route.continue());
  await save.click(); await expect(save).toBeDisabled();
  await expect(reason).toHaveValue("Retained recipient check");
  await page.unroute("**/api/medical/document-grants/");
  await dialog.getByRole("button", { name: kk["common.retry"], exact: true }).click();
  await expect(save).toBeEnabled();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: info.outputPath("issuance-kk-mobile.png") });
  await page.route("**/api/medical/document-grants/", route => route.request().method() === "POST" ? route.fulfill({ status: 403, json: { detail: "Synthetic revoked" } }) : route.continue());
  await save.click();
  await expect(dialog.getByText(kk["medical.denied"], { exact: true })).toBeVisible();
  await expect(reason).toHaveCount(0);
  await expect(dialog.getByText(entry.title)).toHaveCount(0);
  await page.screenshot({ path: info.outputPath("issuance-denied-mobile.png") });
});
