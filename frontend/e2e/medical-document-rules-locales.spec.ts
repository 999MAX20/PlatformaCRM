import { test, expect } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { kk } from "../src/lib/i18n/kk";
import { en } from "../src/lib/i18n/en";
import { requireIsolatedEnvironment } from "./isolated-environment.mjs";

requireIsolatedEnvironment();
for (const language of ["kk", "en"] as const) test(`service override ${language}: independent requirements and preserved history`, async ({ page }, info) => {
  test.setTimeout(120_000);
  const t = { kk, en }[language];
  const output = execFileSync(process.env.E2E_PYTHON!, ["e2e/clinical-runtime.py", "template-new-service"],
    { env: process.env, windowsHide: true, encoding: "utf8" });
  const service = JSON.parse(output.trim().split(/\r?\n/).at(-1)!);
  const name = `Synthetic rules ${crypto.randomUUID()}`;
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.addInitScript(value => localStorage.setItem("ai_smb_language", value), language);
  await page.goto("/login");
  await page.locator('input[name="email"]').fill("medical-template-head@example.test");
  await page.locator('input[name="password"]').fill(process.env.E2E_PASSWORD!);
  await page.locator('form button[type="submit"]').click();
  await expect(page).toHaveURL(/\/app\//);
  await page.goto("/app/settings#medical-templates");
  const workspace = page.getByTestId("medical-template-workspace");
  await workspace.getByRole("button", { name: t["medical.rules.title"], exact: true }).click();
  const rules = page.getByTestId("document-rules");
  await rules.getByRole("button", { name: t["medical.rules.create"], exact: true }).click();
  const form = rules.getByTestId("medical-role-command");
  await form.getByLabel(t["medical.rules.name"], { exact: true }).fill(name);
  const services = form.getByTestId("template-services");
  await services.getByRole("button", { name: t["medical.templates.selectServices"], exact: true }).click();
  await services.getByLabel(t["medical.templates.searchServices"], { exact: true }).fill(service.name);
  await services.getByLabel(t["medical.templates.searchServices"], { exact: true }).press("Enter");
  await services.getByRole("button", { name: service.name, exact: true }).click();
  await services.getByRole("button", { name: t["medical.templates.selectServices"], exact: true }).click();
  const override = form.locator("details").filter({ has: page.locator("summary", { hasText: service.name }) });
  await override.locator("summary").click();
  await override.getByRole("combobox", { name: `${t["medical.rules.moment"]} ${t["medical.rules.moment.optional"]}`, exact: true }).click();
  await page.getByRole("option", { name: t["medical.rules.moment.before_issue"], exact: true }).click();
  await override.getByLabel(t["medical.rules.issuable"], { exact: true }).check();
  await override.getByRole("combobox", { name: `${t["medical.fields.choose"]} ${t["common.select"]}`, exact: true }).click();
  await page.getByRole("option", { name: t["medical.fullName"], exact: true }).click();
  await override.getByRole("button", { name: t["medical.rules.addField"], exact: true }).click();
  await override.getByRole("combobox", { name: `${t["medical.rules.signer"]} ${t["common.select"]}`, exact: true }).click();
  await page.getByRole("option", { name: t["medical.rules.role.patient_or_representative"], exact: true }).click();
  await override.getByRole("button", { name: t["medical.rules.addSigner"], exact: true }).click();
  await override.screenshot({ path: info.outputPath("service-editor-desktop.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  await override.locator("summary").evaluate(element => element.scrollIntoView({ block: "center", behavior: "instant" }));
  await page.screenshot({ path: info.outputPath("service-editor-mobile.png") });
  await override.getByRole("button", { name: t["medical.rules.addSigner"], exact: true })
    .evaluate(element => element.scrollIntoView({ block: "center", behavior: "instant" }));
  await page.screenshot({ path: info.outputPath("service-editor-mobile-bottom.png") });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await form.getByRole("textbox", { name: t["medical.templates.reason"], exact: true }).fill("Synthetic service-specific rule");
  await form.getByRole("button", { name: t["common.save"], exact: true }).click();
  const row = rules.getByRole("listitem").filter({ hasText: name });
  await row.getByRole("button", { name: t["medical.templates.open"], exact: true }).click();
  const detail = rules.getByTestId("document-rule-detail");
  const defaults = detail.locator("section").filter({ has: page.getByRole("heading", { name: t["medical.rules.default"], exact: true }) });
  const savedService = detail.locator("section").filter({ has: page.getByRole("heading", { name: service.name, exact: true }) });
  await expect(defaults).toContainText(t["medical.rules.moment.optional"]);
  await expect(savedService).toContainText(t["medical.rules.moment.before_issue"]);
  await expect(savedService).toContainText(t["medical.fullName"]);
  await expect(savedService).toContainText(t["medical.rules.role.patient_or_representative"]);
  await savedService.screenshot({ path: info.outputPath("service-summary-mobile.png") });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await savedService.screenshot({ path: info.outputPath("service-summary-desktop.png") });
  await detail.getByRole("button", { name: t["medical.templates.newVersion"], exact: true }).click();
  await form.getByTestId("template-services").getByRole("button", { name: `${t["medical.templates.removeService"]}: ${service.name}`, exact: true }).click();
  await expect(form.locator("summary", { hasText: service.name })).toHaveCount(0);
  await form.getByRole("textbox", { name: t["medical.templates.reason"], exact: true }).fill("Synthetic use default rule");
  await form.getByRole("button", { name: t["common.save"], exact: true }).click();
  await row.getByRole("button", { name: t["medical.templates.open"], exact: true }).click();
  await expect(savedService).toHaveCount(0);
  await detail.getByRole("button", { name: t["medical.templates.version"].replace("{revision}", "1"), exact: true }).click();
  await expect(savedService).toContainText(t["medical.rules.moment.before_issue"]);
});
