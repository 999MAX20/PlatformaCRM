import { test, expect } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { ru } from "../src/lib/i18n/ru";
import { requireIsolatedEnvironment } from "./isolated-environment.mjs";
requireIsolatedEnvironment();
test("owner configures reception duty with private recovery and mobile layout", async ({ page }, info) => {
  const entry=JSON.parse(execFileSync(process.env.E2E_PYTHON!,["e2e/clinical-runtime.py","reception-duty-prepare"],{env:process.env,windowsHide:true,encoding:"utf8"}).trim().split(/\r?\n/).at(-1)!);
  await page.addInitScript(() => localStorage.setItem("ai_smb_language","ru"));
  await page.goto("/login");
  await page.locator('input[name="email"]').fill(entry.owner_email);
  await page.locator('input[name="password"]').fill(process.env.E2E_PASSWORD!);
  await page.locator('form button[type="submit"]').click();
  await expect(page).toHaveURL(/\/app\//);
  await page.goto("/app/settings#medical-access");
  await page.getByRole("button",{name:ru["medical.reception.duty"],exact:true}).click();
  const form=page.getByTestId("reception-duty");
  await form.getByRole("combobox",{name:new RegExp(`^${ru["medical.branch"]}`)}).click();
  await page.getByRole("option",{name:"Synthetic completion branch",exact:true}).click();
  await form.getByRole("combobox",{name:new RegExp(`^${ru["medical.reception.dutyLead"]}`)}).click();
  await page.getByRole("option",{name:"Synthetic shift lead",exact:true}).click();
  await form.getByRole("combobox",{name:new RegExp(`^${ru["medical.reception.dutyDeputy"]}`)}).click();
  await page.getByRole("option",{name:"Synthetic shift deputy",exact:true}).click();
  await form.getByLabel(ru["medical.reception.dutyStart"],{exact:true}).fill("2026-11-24T08:00");
  await form.getByLabel(ru["medical.reception.dutyEnd"],{exact:true}).fill("2026-11-24T20:00");
  const reason=form.getByRole("textbox",{name:ru["medical.reception.contactReason"],exact:true});
  await reason.fill("Synthetic agreed shift");
  const save=form.getByRole("button",{name:ru["medical.reception.dutySave"],exact:true});
  await expect(save).toBeEnabled();
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:info.outputPath("duty-desktop.png")});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:info.outputPath("duty-mobile.png")});
  const path="**/api/medical/role-management/reception-duty/";
  await page.route(path,route=>route.request().method()==="POST"?route.fulfill({status:503,json:{detail:"Synthetic unavailable"}}):route.continue());
  await save.click(); await expect(form.getByRole("alert")).toBeVisible(); await expect(reason).toHaveValue("Synthetic agreed shift");
  await page.unroute(path); await save.click(); await expect(form).toHaveCount(0);
  await expect(page.getByRole("button",{name:ru["medical.reception.duty"],exact:true})).toBeFocused();
  await page.getByRole("button",{name:ru["medical.reception.duty"],exact:true}).click();
  await form.getByRole("combobox",{name:new RegExp(`^${ru["medical.branch"]}`)}).click();
  await page.getByRole("option",{name:"Synthetic completion branch",exact:true}).click();
  await expect(form.getByLabel(ru["medical.reception.dutyEnd"],{exact:true})).toHaveValue("2026-11-24T20:00");
  await form.getByRole("checkbox",{name:ru["medical.reception.leadAvailable"],exact:true}).uncheck();
  await reason.fill("Synthetic lead absent, deputy available"); await save.click(); await expect(form).toHaveCount(0);
});


test("open queue receives a fresh request and keeps a contact draft during polling", async ({ page }, info) => {
  const fixture=(command:string,args:string[]=[])=>JSON.parse(execFileSync(process.env.E2E_PYTHON!,["e2e/clinical-runtime.py",command,...args],{env:process.env,windowsHide:true,encoding:"utf8"}).trim().split(/\r?\n/).at(-1)!);
  const entry=fixture("reception-duty-prepare");
  await page.addInitScript(()=>localStorage.setItem("ai_smb_language","ru"));await page.goto("/login");
  await page.locator('input[name="email"]').fill(entry.lead_email);await page.locator('input[name="password"]').fill(process.env.E2E_PASSWORD!);
  await page.locator('form button[type="submit"]').click();await expect(page).toHaveURL(/\/app\//);
  await page.goto("/app/medical/reception");await expect(page.getByText(ru["medical.reception.empty"],{exact:true})).toBeVisible();
  const request=fixture("reception-duty-request",[String(entry.appointment_id)]);
  await page.getByRole("button",{name:ru["header.notifications"],exact:true}).click();
  const notice=page.getByTestId("notification-menu-row").filter({hasText:/пациент сейчас подойдёт/});
  await expect(notice).toBeVisible({timeout:6000});
  await expect(notice).toContainText("Synthetic completion patient");
  await page.screenshot({path:info.outputPath("reception-notice-desktop.png")});
  await notice.getByRole("button").first().click();
  await expect(page).toHaveURL(new RegExp(`branch=${entry.branch_id}&request=${request.request_id}`));
  const row=page.getByTestId(`reception-request-${request.request_id}`);
  await expect(row).toBeVisible({timeout:6000});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:info.outputPath("reception-target-mobile.png")});
  await row.getByRole("button",{name:ru["medical.reception.claim"],exact:true}).click();
  await row.getByRole("button",{name:ru["medical.reception.contactTitle"],exact:true}).click();
  const reason=page.getByTestId("reception-contact").getByRole("textbox",{name:ru["medical.reception.contactReason"],exact:true});
  await reason.fill("Synthetic unsaved contact");
  await page.clock.install();await page.clock.fastForward(7000);
  await expect(reason).toHaveValue("Synthetic unsaved contact");
  page.once("dialog",dialog=>dialog.accept());await page.getByRole("button",{name:ru["common.back"],exact:true}).click();
  await page.route("**/api/reception/booking-requests/?*",route=>route.fulfill({status:403,json:{detail:"Synthetic revoked"}}));
  await page.clock.fastForward(4000);await expect(row).toHaveCount(0);
});
