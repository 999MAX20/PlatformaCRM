import { expect, test } from "@playwright/test";
import { crmSession } from "./support/crm-workspace";
import { ru } from "../src/lib/i18n/ru";
import { en } from "../src/lib/i18n/en";
import { kk } from "../src/lib/i18n/kk";
import type { Task } from "../src/types";

test.beforeEach(() => { test.skip(process.env.ZANI_QUALITY_GATE !== "1", "Disposable task fixtures required"); test.setTimeout(150_000); });
test.use({ actionTimeout: 15_000 });

for (const [locale, dict] of [["ru", ru], ["kk", kk], ["en", en]] as const) {
  test(`task list, inspector, waiting and draft recovery ${locale}`, async ({ page }, testInfo) => {
    const session = await crmSession(page);
    const title = `Task ${locale} ${Date.now()}`;
    const task = await session.create<Task>("tasks", { title, assignee: session.userId, due_at: "2025-01-01T10:00:00Z", description: "Confirm the visit" });
    await page.evaluate(language => localStorage.setItem("ai_smb_language", language), locale);
    await page.goto("/app/tasks");
    await expect(page.getByTestId("task-inspector")).toHaveCount(0);
    await page.getByRole("textbox", { name: dict["taskWorkspace.search"], exact: true }).fill(title);
    const row = page.getByTestId("task-row").filter({ hasText: title });
    await expect(row).toBeVisible();
    await row.focus();
    await page.keyboard.press("Enter");
    const inspector = page.getByTestId("task-inspector");
    await expect(inspector.getByRole("heading", { name: title, exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath(`inspector-${locale}.png`), fullPage: true });
    await inspector.getByRole("button", { name: dict["taskWorkspace.actions"], exact: true }).click();
    await page.getByRole("menuitem", { name: dict["taskWorkspace.wait"], exact: true }).click();
    const waiting = page.getByRole("dialog", { name: dict["taskWorkspace.wait"], exact: true });
    await waiting.getByLabel(dict["taskWorkspace.waitingReason"], { exact: true }).fill("Waiting for confirmation");
    await waiting.getByRole("button", { name: dict["taskWorkspace.save"], exact: true }).click();
    await expect(waiting).toBeHidden();
    await expect.poll(async () => (await session.read(`tasks/${task.id}`)).status).toBe("waiting");
    await expect(inspector.getByText(dict["taskWorkspace.overdue"], { exact: true })).toBeVisible();
    await inspector.getByRole("button", { name: dict["taskWorkspace.resume"], exact: true }).click();
    await expect.poll(async () => (await session.read(`tasks/${task.id}`)).status).toBe("in_progress");
    await inspector.getByRole("button", { name: dict["taskWorkspace.edit"], exact: true }).click();
    const editor = page.getByTestId("task-editor");
    await editor.getByLabel(dict["taskWorkspace.name"], { exact: true }).fill(title + " edited");
    await page.route(`**/api/tasks/${task.id}/update-details/`, route => route.fulfill({ status: 503, json: { detail: "Retry" } }), { times: 1 });
    await editor.getByRole("button", { name: dict["taskWorkspace.save"], exact: true }).click();
    await expect(editor.getByRole("alert")).toBeVisible();
    await expect(editor.getByLabel(dict["taskWorkspace.name"], { exact: true })).toHaveValue(title + " edited");
    await editor.getByRole("button", { name: dict["taskWorkspace.save"], exact: true }).click();
    await expect(editor).toBeHidden();
    await inspector.getByRole("textbox", { name: dict["taskWorkspace.comment"], exact: true }).fill("Draft comment");
    await inspector.getByRole("button", { name: dict["taskWorkspace.close"], exact: true }).click();
    await page.getByRole("button", { name: dict["taskWorkspace.keepEditing"], exact: true }).click();
    await expect(inspector.getByRole("textbox", { name: dict["taskWorkspace.comment"], exact: true })).toHaveValue("Draft comment");
    await inspector.getByRole("button", { name: dict["taskWorkspace.send"], exact: true }).click();
    await expect(inspector.getByRole("textbox", { name: dict["taskWorkspace.comment"], exact: true })).toHaveValue("");
    await inspector.getByRole("link", { name: dict["taskWorkspace.expand"], exact: true }).click();
    await expect(page).toHaveURL(new RegExp(`/app/tasks/${task.id}$`));
    await page.getByRole("button", { name: dict["taskWorkspace.back"], exact: true }).click();
    await expect(page.getByRole("textbox", { name: dict["taskWorkspace.search"], exact: true })).toHaveValue(title);
    await page.getByRole("button", { name: dict["taskWorkspace.close"], exact: true }).click();
    await page.getByRole("button", { name: dict["taskWorkspace.create"], exact: true }).click();
    await page.getByTestId("task-editor").getByLabel(dict["taskWorkspace.name"], { exact: true }).fill("Created " + title);
    await page.getByTestId("task-editor").getByRole("button", { name: dict["taskWorkspace.save"], exact: true }).click();
    await expect(page.getByTestId("task-editor")).toBeHidden();
    await expect(inspector.getByRole("heading", { name: "Created " + title, exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  });
}

test("filters, links, stale edit recovery and terminal actions", async ({ page }, testInfo) => {
  const s = await crmSession(page);
  const title = `Workflow ${Date.now()}`;
  const client = await s.create<{id:number}>("clients", { full_name: title + " Client" });
  const task = await s.create<Task>("tasks", { title, assignee: s.userId });
  await page.evaluate(() => localStorage.setItem("ai_smb_language", "en"));
  await page.goto(`/app/tasks?search=${encodeURIComponent(title)}`);
  const row = page.getByTestId("task-row");
  await expect(row).toHaveCount(1);
  await page.getByRole("button", { name: /^Overdue/ }).click();
  await expect(page.getByText(en["taskWorkspace.noResults"], { exact: true })).toBeVisible();
  await page.getByRole("button", { name: /^No deadline/ }).click();
  await expect(row).toHaveCount(1);
  await page.getByRole("button", { name: en["taskWorkspace.filters"], exact: true }).click();
  await page.getByRole("combobox", { name: en["taskWorkspace.filters"], exact: true }).click();
  await page.getByRole("option", { name: en["taskWorkspace.created"], exact: true }).click();
  await expect(row).toHaveCount(1);
  await page.getByRole("combobox", { name: en["taskWorkspace.filters"], exact: true }).click();
  await page.getByRole("option", { name: en["taskWorkspace.watching"], exact: true }).click();
  await expect(page.getByText(en["taskWorkspace.noResults"], { exact: true })).toBeVisible();
  await s.action(`tasks/${task.id}/add-watcher`);
  await page.reload();
  await expect(row).toHaveCount(1);
  await page.getByRole("button", { name: en["taskWorkspace.team"], exact: true }).click();
  await expect(page.getByRole("table")).toBeVisible();
  await page.getByRole("table").getByRole("button").first().click();
  await expect(row).toHaveCount(1);
  await row.click();
  const inspector = page.getByTestId("task-inspector");
  await inspector.getByRole("button", { name: en["taskWorkspace.edit"], exact: true }).click();
  const editor = page.getByTestId("task-editor");
  await editor.getByLabel(en["taskWorkspace.name"], { exact: true }).fill(title + " local");
  await editor.getByRole("button", { name: en["taskWorkspace.more"], exact: true }).click();
  await editor.getByRole("textbox", { name: en["taskWorkspace.linkSearch"], exact: true }).fill(title);
  await editor.getByRole("combobox", { name: /^Client / }).click();
  await page.getByRole("option", { name: title + " Client", exact: true }).click();
  const changed = await page.request.patch(`${process.env.E2E_API_BASE_URL || "http://127.0.0.1:8000"}/api/tasks/${task.id}/update-details/`, { headers: s.headers, data: { description: "Concurrent change" } });
  expect(changed.ok()).toBeTruthy();
  await editor.getByRole("button", { name: en["taskWorkspace.save"], exact: true }).click();
  await expect(editor.getByText(en["taskWorkspace.conflict"], { exact: true })).toBeVisible();
  await editor.getByRole("button", { name: en["taskWorkspace.refresh"], exact: true }).click();
  await expect(editor.getByLabel(en["taskWorkspace.name"], { exact: true })).toHaveValue(title + " local");
  await editor.getByRole("button", { name: en["taskWorkspace.save"], exact: true }).click();
  await expect(editor).toBeHidden();
  expect((await s.read(`tasks/${task.id}`)).description).toBe("Concurrent change");
  await expect(inspector.locator(`a[href='/app/clients/${client.id}']`)).toBeVisible();
  await inspector.getByRole("button", { name: en["taskWorkspace.complete"], exact: true }).click();
  await expect(inspector.getByRole("button", { name: en["taskWorkspace.reopen"], exact: true })).toBeVisible();
  await inspector.getByRole("button", { name: en["taskWorkspace.reopen"], exact: true }).click();
  await inspector.getByRole("button", { name: en["taskWorkspace.actions"], exact: true }).click();
  await page.getByRole("menuitem", { name: en["taskWorkspace.cancel"], exact: true }).click();
  const cancel = page.getByRole("dialog", { name: en["taskWorkspace.cancel"], exact: true });
  await cancel.getByRole("textbox", { name: en["taskWorkspace.cancelReason"], exact: true }).fill("No longer needed");
  await cancel.getByRole("button", { name: en["taskWorkspace.save"], exact: true }).click();
  await expect(cancel).toBeHidden();
  await inspector.getByRole("tab", { name: en["taskWorkspace.history"], exact: true }).click();
  await expect(inspector.getByRole("article").first()).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("task-terminal.png"), fullPage: true });
  await inspector.locator(`a[href='/app/clients/${client.id}']`).click();
  await expect(page).toHaveURL(new RegExp(`/app/clients/${client.id}$`));
});

test("list error recovery and view-only inspector", async ({ page }) => {
  const s = await crmSession(page);
  const title = `Read only ${Date.now()}`;
  const task = await s.create<Task>("tasks", { title, assignee: s.userId });
  await page.evaluate(() => localStorage.setItem("ai_smb_language", "en"));
  let fail = true;
  await page.route(/\/api\/tasks\/\?/, route => fail ? route.fulfill({ status: 503, json: { detail: "Unavailable" } }) : route.continue());
  await page.goto(`/app/tasks?search=${encodeURIComponent(title)}`);
  await expect(page.getByRole("alert")).toBeVisible({ timeout: 20000 });
  fail = false;
  await page.getByRole("button", { name: en["taskWorkspace.refresh"], exact: true }).click();
  await expect(page.getByTestId("task-row")).toHaveCount(1);
  await page.route(new RegExp(`/api/tasks/${task.id}/\\?`), async route => {
    const response = await route.fetch();
    await route.fulfill({ response, json: { ...await response.json(), available_actions: [] } });
  });
  await page.getByTestId("task-row").click();
  const inspector = page.getByTestId("task-inspector");
  await expect(inspector.getByRole("heading", { name: title, exact: true })).toBeVisible();
  await expect(inspector.getByRole("button", { name: en["taskWorkspace.edit"], exact: true })).toHaveCount(0);
  await expect(inspector.getByRole("button", { name: en["taskWorkspace.complete"], exact: true })).toHaveCount(0);
  await expect(inspector.getByRole("textbox", { name: en["taskWorkspace.comment"], exact: true })).toHaveCount(0);
});
