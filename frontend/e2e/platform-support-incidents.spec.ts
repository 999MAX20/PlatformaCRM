import { expect, test } from "@playwright/test";
import { ru } from "../src/lib/i18n/ru";
import { kk } from "../src/lib/i18n/kk";
import { en } from "../src/lib/i18n/en";
const api = process.env.E2E_API_BASE_URL || "http://127.0.0.1:8000";
test.beforeEach(() => test.skip(process.env.E2E_PLATFORM_SUPPORT !== "1", "Use the isolated support runner"));

test("support incident links existing and new cases from clinic diagnostics", async ({ page }, info) => {
  test.setTimeout(120_000);
  await page.goto('/login');
  await page.locator('form input[type=email]').fill(`support-team-${info.project.name}@example.com`);
  await page.locator('form input[type=password]').fill(process.env.E2E_PASSWORD || 'ZaniTest123!');
  const tokenResponse=page.waitForResponse(response=>response.url().endsWith('/api/auth/token/')&&response.request().method()==='POST');
  await page.locator('form button[type=submit]').click();
  const token=await (await tokenResponse).json();
  await expect(page).toHaveURL(/\/platform/);
  const headers={Authorization:`Bearer ${token.access}`};
  const clinics=await page.request.get(`${api}/api/platform/merchants/`,{headers,params:{search:`Support Clinic ${info.project.name}`}});
  const business=(await clinics.json()).results[0].id;
  await page.goto(`/platform/merchants/${business}`);
  await page.getByRole('link',{name:ru['supportIncidents.open'],exact:true}).click();
  await expect(page.getByTestId('support-incident-page')).toBeVisible();
  await expect(page.getByText(ru['supportIncidents.noCases'],{exact:true})).toBeVisible();
  await page.getByRole('combobox',{name:ru['supportIncidents.existing']}).click();
  await page.getByRole('option').filter({hasText:`Queue fixture ${info.project.name}`}).first().click();
  const failureRoute=/\/api\/platform\/support-cases\/\d+\/incidents\/$/;
  await page.route(failureRoute,route=>route.request().method()==='POST'?route.fulfill({status:503,contentType:'application/json',body:'{"code":"temporary_service_failure"}'}):route.continue());
  const failed=page.waitForResponse(response=>failureRoute.test(response.url())&&response.status()===503);
  await page.getByRole('button',{name:ru['supportIncidents.link'],exact:true}).click();await failed;
  await expect(page.getByRole('combobox',{name:ru['supportIncidents.existing']})).toContainText(`Queue fixture ${info.project.name}`);
  await page.unroute(failureRoute);
  await page.getByRole('button',{name:ru['supportIncidents.link'],exact:true}).click();
  await expect(page.getByText(ru['supportIncidents.linked'],{exact:true})).toBeVisible();
  await page.getByRole('link').filter({hasText:`Queue fixture ${info.project.name}`}).click();
  await expect(page.getByTestId('support-incident-links')).toContainText(ru['supportIncidents.snapshot']);
  await page.getByTestId('support-incident-links').getByRole('link',{name:ru['supportIncidents.open'],exact:true}).click();
  await page.getByRole('button',{name:ru['supportCases.create'],exact:true}).click();
  const dialog=page.getByTestId('support-create-dialog');
  await expect(dialog.getByRole('combobox').filter({hasText: 'Support Clinic'})).toBeDisabled();
  await dialog.getByRole('textbox',{name:ru['supportCases.subject'],exact:true}).fill(`Incident ${info.project.name}`);
  await dialog.getByRole('textbox',{name:ru['supportCases.description'],exact:true}).fill('Please investigate the delayed export');
  await dialog.getByRole('button',{name:ru['supportCases.submit'],exact:true}).click();
  await expect(page.getByTestId('support-case-detail')).toBeVisible();
  await expect(page.getByTestId('support-incident-links')).toContainText(ru['supportIncidents.snapshot']);
  await page.getByTestId('support-incident-links').getByRole('link',{name:ru['supportIncidents.open'],exact:true}).click();
  await expect(page.getByRole('link').filter({hasText:`Incident ${info.project.name}`})).toBeVisible();
  await page.getByRole('combobox',{name:ru['supportIncidents.existing']}).focus();
  await expect(page.getByRole('combobox',{name:ru['supportIncidents.existing']})).toBeFocused();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
  await page.screenshot({path:info.outputPath('incident.png'),fullPage:true});
  for (const [language, copy] of [["kk", kk], ["en", en]] as const) {
    await page.evaluate(value => localStorage.setItem("ai_smb_language", value), language);
    await page.reload();
    await expect(page.getByRole('heading', {name:copy['supportIncidents.open'],exact:true})).toBeVisible();
    await page.getByRole('combobox',{name:copy['supportIncidents.existing']}).focus();
    await expect(page.getByRole('combobox',{name:copy['supportIncidents.existing']})).toBeFocused();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
    await page.screenshot({path:info.outputPath(`incident-${language}.png`),fullPage:true});
  }
});
