async function choose(page: Page, label: string, option: string) {
  await page.getByRole("combobox", { name: new RegExp("^" + label.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")) }).click();
  await page.getByRole("option", { name: option, exact: true }).click();
}

test("save branch access for an employee and location scope for a customer agent", async ({ page }) => {
  const session = await crmSession(page);
  const branch = await session.create<Branch>("branches", { name: `Scope ${Date.now()}`, address: "Abay 30" });
  const member = (await session.list<TeamMember>("team/members")).find((item) => item.role === "operator")!;
  await page.goto("/app/settings#team-access");
  await page.locator("#team-access").getByRole("button").filter({ hasText: member.user.email }).click();
  const grant = page.getByRole("group", { name: ru["branches.access"], exact: true });
  await grant.getByRole("checkbox", { name: branch.name, exact: true }).check();
  await grant.getByRole("button", { name: ru["common.save"], exact: true }).click();
  await expect.poll(async () => (await session.read(`team/members/${member.id}`)).branch_access.branch_ids).toContain(branch.id);
  const bot = await session.create<Bot>("bots", { name: `Reception ${Date.now()}`, status: "draft" });
  await session.create<AgentProfile>("ai/agent-profiles", { bot: bot.id, name: bot.name, allowed_tools_json: { tools: ["handoff_to_manager"] } });
  await page.goto(`/app/ai-agents/${bot.id}/profile`);
  const scope = page.getByRole("group", { name: ru["branches.agentScope"], exact: true });
  await scope.getByRole("checkbox", { name: ru["branches.allFuture"], exact: true }).uncheck();
  for (const checkbox of await scope.getByRole("checkbox").all()) if (await checkbox.isChecked()) await checkbox.uncheck();
  await scope.getByRole("checkbox", { name: `${branch.name} · ${branch.address}`, exact: true }).check();
  await page.getByTestId("ai-agent-editor").getByRole("button", { name: ru["aiAgents.saveChanges"], exact: true }).click();
  await expect.poll(async () => (await session.read(`bots/${bot.id}`)).settings_json.branch_ids).toEqual([branch.id]);
  await page.reload();
  await expect(scope.getByRole("checkbox", { name: `${branch.name} · ${branch.address}`, exact: true })).toBeChecked();
});

test("configure branch services, specialist intervals and recover a failed save", async ({ page }, testInfo) => {
  const session = await crmSession(page);
  const suffix = Date.now();
  const service = await session.create<Service>("services", { name: `Consult ${suffix}`, duration_minutes: 30 });
  const staff = await session.create<Resource>("resources", { name: `Doctor ${suffix}`, resource_type: "staff" });
  await page.goto("/app/business/branches");
  await page.getByRole("button", { name: ru["branches.add"], exact: true }).click();
  await page.getByLabel(ru["branches.name"], { exact: true }).fill(`North ${suffix}`);
  await page.getByLabel(ru["branches.address"], { exact: true }).fill("Abay 15");
  await page.getByRole("button", { name: ru["common.save"], exact: true }).click();
  await expect.poll(async () => (await session.list<Branch>("branches")).some((item) => item.name === `North ${suffix}`)).toBeTruthy();
  const branch = (await session.list<Branch>("branches")).find((item) => item.name === `North ${suffix}`)!;
  await page.getByRole("button", { name: ru["branches.services"], exact: true }).click();
  await choose(page, ru["appointment.service"], service.name);
  await page.getByLabel(ru["branches.duration"], { exact: true }).fill("45");
  await page.getByLabel(ru["branches.price"], { exact: true }).fill("18000");
  await page.route(`**/api/branches/${branch.id}/offers/`, (route) => route.fulfill({ status: 503, json: { detail: "Please retry" } }), { times: 1 });
  await page.getByRole("button", { name: ru["common.save"], exact: true }).click();
  await expect(page.getByRole("alert")).toBeVisible();
  await expect(page.getByLabel(ru["branches.price"], { exact: true })).toHaveValue("18000");
  await page.getByRole("button", { name: ru["common.save"], exact: true }).click();
  await expect.poll(async () => (await session.read(`branches/${branch.id}/configuration`) as BranchConfiguration).offers.find((item) => item.service === service.id)?.duration_minutes).toBe(45);
  await page.getByRole("button", { name: ru["branches.specialists"], exact: true }).click();
  await choose(page, ru["appointment.resource"], staff.name);
  await page.getByRole("checkbox", { name: service.name, exact: true }).check();
  await page.getByRole("button", { name: ru["common.save"], exact: true }).click();
  await expect.poll(async () => (await session.read(`branches/${branch.id}/configuration`) as BranchConfiguration).assignments.some((item) => item.resource === staff.id && item.service_ids.includes(service.id))).toBeTruthy();
  await page.getByRole("button", { name: ru["branches.schedule"], exact: true }).click();
  await choose(page, ru["branches.scheduleFor"], staff.name);
  // A pre-existing first-branch specialist can already have an adopted day-off row.
  for (let index = await page.getByRole("button", { name: ru["branches.removeInterval"], exact: true }).count(); index > 0; index--) await page.getByRole("button", { name: ru["branches.removeInterval"], exact: true }).first().click();
  await page.getByRole("button", { name: ru["branches.addInterval"], exact: true }).click();
  await page.getByLabel(ru["branches.end"], { exact: true }).fill("12:00");
  await page.getByRole("button", { name: ru["branches.addInterval"], exact: true }).click();
  await page.getByLabel(ru["branches.start"], { exact: true }).nth(1).fill("14:00");
  await page.getByRole("button", { name: ru["branches.removeInterval"], exact: true }).nth(1).focus();
  await page.keyboard.press("Tab");
  await expect(page.getByRole("button", { name: ru["branches.addInterval"], exact: true })).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("button", { name: ru["branches.removeInterval"], exact: true })).toHaveCount(3);
  await page.getByRole("button", { name: ru["branches.removeInterval"], exact: true }).last().click();
  await page.getByRole("button", { name: ru["common.save"], exact: true }).click();
  await expect.poll(async () => (await session.read(`branches/${branch.id}/configuration`) as BranchConfiguration).days.find((item) => item.resource === staff.id && item.weekday === 0)?.intervals.length).toBe(2);
  await expect(page.getByRole("button", { name: ru["common.save"], exact: true })).toBeEnabled();
  await page.screenshot({ path: testInfo.outputPath("branch-schedule.png"), fullPage: true });
});

for (const [locale, dict] of [["ru", ru], ["kk", kk], ["en", en]] as const) {
  test(`booking uses branch terms and staff absence/retirement preserves visits ${locale}`, async ({ page }, testInfo) => {
    const session = await crmSession(page);
    const suffix = `${locale}-${Date.now()}`;
    const client = await session.create<Client>("clients", { full_name: `Patient ${suffix}` });
    const branch = await session.create<Branch>("branches", { name: `Clinic ${suffix}`, address: "Abay 25" });
    const service = await session.create<Service>("services", { name: `Check ${suffix}`, duration_minutes: 30, price_from: "10000" });
    const staff = await session.create<Resource>("resources", { name: `Specialist ${suffix}`, resource_type: "staff" });
    await session.action(`branches/${branch.id}/offers`, { service: service.id, duration_minutes: 60, price_from: "25000" });
    await session.action(`branches/${branch.id}/assignments`, { resource: staff.id, service_ids: [service.id] });
    for (const resource of [null, staff.id]) await session.action(`branches/${branch.id}/schedule`, { resource, date: "2030-01-07", intervals: [{ start: "09:00", end: "18:00" }] });
    await page.evaluate((language) => localStorage.setItem("ai_smb_language", language), locale);
    await page.goto(`/app/calendar?date=2030-01-07&branch=${branch.id}`);
    await page.getByRole("button", { name: dict["calendar.newBooking"], exact: true }).first().click();
    const form = page.getByTestId("appointment-form");
    await expect(form.getByRole("combobox", { name: new RegExp("^" + dict["branches.branch"]) })).toContainText(branch.name);
    await choose(page, dict["appointment.client"], client.full_name);
    await choose(page, dict["appointment.service"], `${service.name} · 60 ${dict["appointment.minutes"]}`);
    await choose(page, dict["appointment.resource"], staff.name);
    await form.getByRole("combobox", { name: new RegExp("^" + dict["appointment.slot"]) }).click();
    await page.getByRole("option", { name: locale === "en" ? "09:00 AM" : "09:00", exact: true }).click();
    await form.getByTestId("appointment-submit").click();
    await expect(form).not.toBeVisible();
    const visit = (await session.list<Appointment>("appointments")).find((item) => item.resource === staff.id)!;
    expect(visit).toMatchObject({ branch: branch.id, booked_duration_minutes: 60, booked_price: "25000.00", branch_address: "Abay 25" });
    await page.goto(`/app/calendar/${visit.id}`);
    await page.locator('[data-appointment-action-id="reschedule"]').click();
    const reschedule = page.getByTestId("appointment-reschedule-form");
    await reschedule.getByRole("combobox", { name: new RegExp("^" + dict["appointment.time"]) }).click();
    await page.getByRole("option", { name: locale === "en" ? "10:00 AM - 11:00 AM" : "10:00 - 11:00", exact: true }).click();
    await reschedule.getByTestId("appointment-reschedule-submit").click();
    await expect(reschedule).not.toBeVisible();
    expect((await session.read(`appointments/${visit.id}`)).start_at).not.toBe(visit.start_at);
    expect(await session.read(`appointments/${visit.id}`)).toMatchObject({ branch: branch.id, booked_duration_minutes: 60, booked_price: "25000.00", status: "created" });
    await page.goto(`/app/business/resources?resource=${staff.id}`);
    const modal = page.getByTestId("resource-edit-modal");
    await modal.getByLabel(dict["branches.absenceStart"], { exact: true }).fill("2030-01-07");
    await modal.getByLabel(dict["branches.absenceEnd"], { exact: true }).fill("2030-01-08");
    await modal.getByRole("button", { name: dict["branches.addAbsence"], exact: true }).click();
    await expect(modal.getByRole("button", { name: dict["branches.removeAbsence"], exact: true })).toBeVisible();
    expect((await session.read(`appointments/${visit.id}`)).status).toBe("created");
    const slots = await session.read("appointments/available-slots", { business_id: session.business, service_id: service.id, resource_id: staff.id, branch_id: branch.id, date: "2030-01-07" });
    expect(slots).toEqual([]);
    await modal.getByRole("button", { name: dict["branches.retire"], exact: true }).click();
    await expect(modal.getByRole("button", { name: dict["branches.retire"], exact: true }).last()).toBeDisabled();
    await page.screenshot({ path: testInfo.outputPath(`specialist-${locale}.png`), fullPage: true });
    await session.action(`appointments/${visit.id}/cancel`, { reason: "Reassigned manually" });
    await page.goto(`/app/calendar?date=2030-01-07&appointment=${visit.id}`);
    await page.getByRole("button", { name: dict["appointments.repeatBooking"], exact: true }).click();
    await expect(page.getByTestId("appointment-form").getByRole("combobox", { name: new RegExp("^" + dict["branches.branch"]) })).toContainText(branch.name);
    await page.goto(`/app/business/resources?resource=${staff.id}`);
    await modal.getByRole("button", { name: dict["branches.retire"], exact: true }).click();
    await expect(modal.getByRole("button", { name: dict["branches.retire"], exact: true })).toHaveCount(2);
    await modal.getByRole("button", { name: dict["branches.retire"], exact: true }).last().click();
    await page.getByRole("dialog").filter({ hasText: dict["branches.retireConfirm"] }).getByRole("button", { name: dict["actions.confirm"], exact: true }).click();
    await expect(modal.getByText(dict["branches.retired"], { exact: true })).toBeVisible();
    expect((await session.read(`appointments/${visit.id}`)).resource).toBe(staff.id);
  });
}
