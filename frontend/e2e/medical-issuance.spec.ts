test("issuance KK retains input on failure and clears denied data", async ({ page }, info) => {
  const entry = JSON.parse(execFileSync(process.env.E2E_PYTHON!, ["e2e/clinical-runtime.py", "issuance-prepare"],
    { env: process.env, windowsHide: true, encoding: "utf8" }).trim().split(/\r?\n/).at(-1)!);
  await page.addInitScript(() => localStorage.setItem("ai_smb_language", "kk"));
  await page.goto("/login");
  await page.locator('input[name="email"]').fill(entry.email);
  await page.locator('input[name="password"]').fill(process.env.E2E_PASSWORD!);
  await page.locator('form button[type="submit"]').click();
  await expect(page).toHaveURL(/\/app\//);
  await page.goto(`/app/clients/${entry.client_id}`);
  const administration = page.getByTestId("patient-administration");
  await administration.getByLabel(kk["medical.branch"], { exact: true }).click();
  await page.getByRole("option", { name: "Synthetic completion branch", exact: true }).click();
  await administration.getByRole("button", { name: kk["medical.issue.title"], exact: true }).click();
  const dialog = page.getByTestId("medical-document-issuance");
  await dialog.getByLabel(kk["medical.issue.encounter"], { exact: true }).click();
  await page.getByRole("option", { name: new RegExp(`№${entry.encounter_id} ·`) }).click();
  await dialog.getByRole("checkbox", { name: new RegExp(entry.title) }).check();
  await dialog.getByRole("checkbox", { name: kk["medical.issue.verified"], exact: true }).check();
  const reason = dialog.getByRole("textbox", { name: kk["medical.issue.verification"], exact: true });
  await reason.fill("Retained recipient check");
  const save = dialog.getByRole("button", { name: kk["medical.issue.create"], exact: true });
  await page.route("**/api/medical/document-grants/", route => route.request().method() === "POST" ? route.fulfill({ status: 503, json: { detail: "Synthetic unavailable" } }) : route.continue());
  await save.click();
  await expect(dialog.getByRole("alert")).toBeVisible();
  await expect(reason).toHaveValue("Retained recipient check");
  await page.unroute("**/api/medical/document-grants/");
  await page.route("**/api/medical/document-grants/", route => route.request().method() === "POST" ? route.fulfill({ status: 409, json: { detail: "Synthetic conflict" } }) : route.continue());
  await save.click(); await expect(save).toBeDisabled();
  await expect(reason).toHaveValue("Retained recipient check");
  await page.unroute("**/api/medical/document-grants/");
  await dialog.getByRole("button", { name: kk["common.retry"], exact: true }).click();
  await expect(save).toBeEnabled();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: info.outputPath("issuance-kk-mobile.png") });
  await page.route("**/api/medical/document-grants/", route => route.request().method() === "POST" ? route.fulfill({ status: 403, json: { detail: "Synthetic revoked" } }) : route.continue());
  await save.click();
  await expect(dialog.getByText(kk["medical.denied"], { exact: true })).toBeVisible();
  await expect(reason).toHaveCount(0);
  await expect(dialog.getByText(entry.title)).toHaveCount(0);
  await page.screenshot({ path: info.outputPath("issuance-denied-mobile.png") });
});
