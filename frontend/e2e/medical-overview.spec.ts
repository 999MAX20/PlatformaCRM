import { test, expect } from "@playwright/test";
import { execFileSync } from "node:child_process";
import AxeBuilder from "@axe-core/playwright";
import { ru } from "../src/lib/i18n/ru";
import { kk } from "../src/lib/i18n/kk";
import { en } from "../src/lib/i18n/en";
import { requireIsolatedEnvironment } from "./isolated-environment.mjs";

requireIsolatedEnvironment();
let nextId = 7;
for (const language of ["ru", "kk", "en"] as const) for (const width of [1440, 390]) {
  const id = ++nextId;
  test(`clinical overview ${language} ${width}: saved source and safe navigation`, async ({ page }, info) => {
    const t = { ru, kk, en }[language];
    execFileSync(process.env.E2E_PYTHON!, ["e2e/clinical-runtime.py", "overview-demographics"], { env: process.env, windowsHide: true, stdio: "pipe" });
    await page.setViewportSize({ width, height: 1000 });
    await page.addInitScript(value => localStorage.setItem("ai_smb_language", value), language);
    await page.goto("/login");
    await page.locator('input[name="email"]').fill("medical-role-doctor@example.test");
    await page.locator('input[name="password"]').fill(process.env.E2E_PASSWORD!);
    const login = page.waitForResponse(r => r.url().endsWith("/api/auth/token/") && r.request().method() === "POST");
    const me = page.waitForResponse(r => r.url().endsWith("/api/auth/me/") && r.status() === 200);
    await page.locator('form button[type="submit"]').click();
    const token = (await (await login).json()).access;
    await me;
    await expect(page).toHaveURL(/\/app\//);
    const appointmentResponse = await page.request.get(`${process.env.E2E_API_BASE_URL}/api/appointments/${id}/`, { headers: { Authorization: `Bearer ${token}` } });
    expect(appointmentResponse.status()).toBe(200);
    const appointment = await appointmentResponse.json();
    await page.goto(`/app/calendar?appointment=${id}&date=${appointment.start_at.slice(0, 10)}`);
    await page.getByTestId("clinical-appointment-entry").getByRole("button", { name: t["medical.clinical.open"], exact: true }).click();
    const workspace = page.getByTestId("clinical-workspace");
    const overviewTab = workspace.getByRole("tab", { name: t["medical.overview.title"], exact: true });
    await overviewTab.click();
    const overview = workspace.getByTestId("clinical-overview");
    await expect(overview.getByText("2000-02-29", { exact: true })).toBeVisible();
    await expect(overview.getByText(t["medical.clinical.historyEmpty"], { exact: true })).toBeVisible();
    await expect(overview.getByTestId("clinical-overview-risks").getByText(t["medical.clinical.notRecorded"], { exact: true })).toHaveCount(2);
    await overview.getByRole("button", { name: t["medical.clinical.note"], exact: true }).click();
    await expect(workspace.getByRole("tab", { name: t["medical.clinical.note"], exact: true })).toBeFocused();
    await workspace.getByLabel(t["medical.clinical.number"], { exact: true }).fill(`OVERVIEW-${id}`);
    await workspace.getByRole("button", { name: t["medical.clinical.createRecord"], exact: true }).click();
    await workspace.getByRole("button", { name: t["medical.clinical.start"], exact: true }).click();
    const allergies = workspace.getByRole("textbox", { name: t["medical.clinical.allergies"], exact: true });
    const recorded = `Synthetic allergy statement ${id}`;
    await allergies.fill(recorded);
    await workspace.getByRole("textbox", { name: t["medical.clinical.contraindications"], exact: true }).fill("Synthetic patient denies contraindications");
    await workspace.getByRole("button", { name: t["medical.clinical.save"], exact: true }).click();
    await expect(workspace.getByText(t["common.saved"], { exact: true })).toBeVisible();
    await allergies.fill("Synthetic unsaved replacement");
    await overviewTab.click();
    await expect(overview.getByText(recorded, { exact: true })).toBeVisible();
    await expect(overview.getByText("Synthetic patient denies contraindications", { exact: true })).toBeVisible();
    await expect(overview.getByText("Synthetic unsaved replacement", { exact: true })).toHaveCount(0);
    await overview.locator("summary").click();
    await expect(overview.getByText(`${t["medical.clinical.revision"]} 2`, { exact: false })).toBeVisible();
    await overview.screenshot({ path: info.outputPath("clinical-overview.png") });
    await workspace.screenshot({ path: info.outputPath("clinical-overview-workspace.png") });
    expect((await new AxeBuilder({ page }).include('[data-testid="clinical-workspace"]').withTags(["wcag2a", "wcag2aa"]).analyze()).violations).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await overview.getByRole("button", { name: t["medical.clinical.note"], exact: true }).click();
    await expect(allergies).toHaveValue("Synthetic unsaved replacement");
    if (language === "en" && width === 390) {
      await page.route("**/api/medical/encounters/overview/**", route => route.fulfill({ status: 503, json: {} }));
      await overviewTab.click();
      await workspace.getByRole("button", { name: t["common.retry"], exact: true }).waitFor();
      await page.unroute("**/api/medical/encounters/overview/**");
      await workspace.getByRole("button", { name: t["common.retry"], exact: true }).click();
      await expect(overview.getByText(recorded, { exact: true })).toBeVisible();
      await overview.getByRole("button", { name: t["medical.clinical.history"], exact: true }).click();
      await expect(workspace.getByRole("tab", { name: t["medical.clinical.history"], exact: true })).toBeFocused();
      await page.route("**/api/medical/encounters/versions/**", route => route.fulfill({ status: 403, json: {} }));
      await overviewTab.click();
      await expect(workspace.getByText(t["medical.denied"], { exact: true })).toBeVisible();
      await expect(overview).toHaveCount(0);
      await workspace.screenshot({ path: info.outputPath("clinical-overview-denied.png") });
    }
  });
}
