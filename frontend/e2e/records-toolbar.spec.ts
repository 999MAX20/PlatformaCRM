import { expect, test } from "@playwright/test";
import { ru } from "../src/lib/i18n/ru";
import { kk } from "../src/lib/i18n/kk";
import { en } from "../src/lib/i18n/en";

for (const [language, copy] of [["ru", ru], ["kk", kk], ["en", en]] as const) {
  test(`records toolbar draft, dates, URL, keyboard and mobile ${language}`, async ({ page }, info) => {
    await page.setViewportSize({ width: language === "ru" ? 1440 : 390, height: 844 });
    await page.addInitScript(value => localStorage.setItem("ai_smb_language", value), language);
    await page.route("**/api/auth/me/", async route => {
      const response = await route.fetch(); const user = await response.json();
      await route.fulfill({ response, json: { ...user, preferences: { ...user.preferences, language } } });
    });
    await page.goto("/login");
    await page.locator('form input[type="email"]').fill("business_owner@example.com");
    await page.locator('form input[type="password"]').fill(process.env.E2E_PASSWORD || "ZaniTest123!");
    await page.locator('form button[type="submit"]').click();
    await expect(page).toHaveURL(/\/app/);
    await page.goto("/app/appointments?from=2026-12-15&to=2026-12-15");
    const links = page.locator('main a[href^="/app/appointments/"]:visible');
    await expect(links).toHaveCount(3);
    await page.goto("/app/clients");
    await page.goto("/app/appointments");
    await expect(page).toHaveURL(/from=2026-12-15/);
    await expect(links).toHaveCount(3);
    const toolbar = page.getByTestId("records-toolbar");
    const trigger = toolbar.locator('[data-focus-return-id="records-filters"]');
    await trigger.click();
    const dialog = page.getByRole("dialog");
    const confirmation = dialog.getByRole("combobox", { name: copy["records.confirmation"] });
    await confirmation.click();
    await page.getByRole("option", { name: copy["records.unconfirmed"], exact: true }).click();
    await expect(page).not.toHaveURL(/confirmed=/);
    await dialog.getByRole("button", { name: copy["common.cancel"], exact: true }).click();
    await expect(trigger).toBeFocused();
    await expect(links).toHaveCount(3);
    await trigger.click();
    await confirmation.click();
    await page.getByRole("option", { name: copy["appointments.confirmed"], exact: true }).click();
    await dialog.getByRole("button", { name: copy["crmFilters.apply"], exact: true }).click();
    await expect(page).toHaveURL(/confirmed=true/);
    await expect(trigger).toContainText("1");
    await expect(links).toHaveCount(1);
    await page.reload();
    await expect(trigger).toContainText("1");
    await trigger.click();
    await confirmation.click();
    await page.getByRole("option", { name: copy["records.all"], exact: true }).click();
    await dialog.getByRole("button", { name: copy["crmFilters.apply"], exact: true }).click();
    await expect(links).toHaveCount(3);
    await page.goBack();
    await expect(trigger).toContainText("1");
    await page.goForward();
    await expect(links).toHaveCount(3);
    await trigger.click();
    await page.keyboard.press("Escape");
    await expect(dialog).toHaveCount(0);
    await expect(trigger).toBeFocused();
    await toolbar.locator('[data-focus-return-id="records-period"]').click();
    await expect(dialog).toHaveCount(0);
    const periodPanel = page.locator("#records-period-panel");
    await periodPanel.locator('[data-date="2026-12-21"]').click();
    await expect(periodPanel.getByRole("button", { name: copy["crmFilters.apply"], exact: true })).toBeDisabled();
    await expect(page).toHaveURL(/from=2026-12-15/);
    await periodPanel.locator('[data-date="2026-12-20"]').click();
    const response = page.waitForResponse(r => r.url().includes("/api/appointments/workspace/") && r.url().includes("start_from=2026-12-20"));
    await periodPanel.getByRole("button", { name: copy["crmFilters.apply"], exact: true }).click();
    expect((await response).url()).toContain("start_to=2026-12-22");
    await expect(page.getByText(copy["appointments.emptyFiltered"], { exact: true })).toBeVisible();
    await toolbar.getByRole("button", { name: copy["records.reset"], exact: true }).click();
    await expect(page).not.toHaveURL(/from=2026-12-/);
    await expect(page.getByText(copy["appointments.emptyFiltered"], { exact: true })).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
    const empty = await page.getByText(copy["appointments.emptyFiltered"], { exact: true }).boundingBox();
    expect(empty!.y + empty!.height).toBeLessThan(760);
    await page.screenshot({ path: info.outputPath(`records-mobile-${language}.png`) });
    await trigger.click();
    await confirmation.click();
    await page.getByRole("option", { name: copy["records.unconfirmed"], exact: true }).click();
    await dialog.getByRole("button", { name: copy["common.reset"], exact: true }).click();
    await expect(confirmation).toContainText(copy["records.all"]);
    await expect(dialog.getByRole("button", { name: copy["crmFilters.apply"], exact: true })).toBeInViewport();
    await page.screenshot({ path: info.outputPath(`records-filters-${language}.png`) });
    await page.keyboard.press("Escape");
    await expect(trigger).toBeFocused();
    await page.setViewportSize({ width: 1440, height: 1000 });
    const row = page.getByTestId("records-toolbar-row");
    expect(await row.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBeTruthy();
    const status = toolbar.getByRole("combobox", { name: copy["records.pipeline"], exact: true });
    await status.click();
    await page.getByRole("option", { name: new RegExp(`^${copy["records.completed"]} ·`) }).click();
    await expect(page).toHaveURL(/workflow=completed/);
    const sort = toolbar.getByRole("button", { name: `${copy["records.ordering"]}: ${copy["records.ascending"]}`, exact: true });
    await sort.click();
    await expect(page).toHaveURL(/ordering=-start_at/);
    await toolbar.getByRole("button", { name: copy["records.reset"], exact: true }).click();
    await page.screenshot({ path: info.outputPath(`records-desktop-${language}.png`) });
    await page.unrouteAll({ behavior: "wait" });
  });
}


test("remembered period respects drilldown links and explicit reset", async ({ page }) => {
  await page.goto("/login");
  await page.locator('form input[type="email"]').fill("business_owner@example.com");
  await page.locator('form input[type="password"]').fill(process.env.E2E_PASSWORD || "ZaniTest123!");
  await page.locator('form button[type="submit"]').click();
  await expect(page).toHaveURL(/\/app/);
  await page.goto("/app/appointments?from=2026-12-15&to=2026-12-15");
  await expect(page.locator('main a[href^="/app/appointments/"]:visible')).toHaveCount(3);
  await page.goto("/app/appointments?attention=pending_result");
  await expect(page.getByTestId("records-toolbar")).toBeVisible();
  await expect(page).not.toHaveURL(/from=/);
  await page.goto("/app/appointments");
  await expect(page).toHaveURL(/from=2026-12-15/);
  await expect(page.locator('main a[href^="/app/appointments/"]:visible')).toHaveCount(3);
  await page.locator('aside a[href="/app/appointments"]').click();
  await expect(page).toHaveURL(/from=2026-12-15/);
  await expect(page.locator('main a[href^="/app/appointments/"]:visible')).toHaveCount(3);
  await page.getByTestId("records-toolbar").getByRole("button", { name: ru["records.reset"], exact: true }).click();
  await expect(page).not.toHaveURL(/from=2026-12-/);
  await page.goto("/app/clients");
  await page.goto("/app/appointments");
  await expect(page.getByTestId("records-toolbar")).toBeVisible();
  await expect(page).not.toHaveURL(/from=2026-12-/);
});
