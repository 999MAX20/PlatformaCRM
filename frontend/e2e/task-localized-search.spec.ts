import { execFileSync } from "node:child_process";
import { expect, test } from "@playwright/test";
import { crmSession } from "./support/crm-workspace";
import { ru } from "../src/lib/i18n/ru";
import { kk } from "../src/lib/i18n/kk";
import { en } from "../src/lib/i18n/en";

test.beforeEach(() => { test.skip(process.env.ZANI_QUALITY_GATE !== "1", "Disposable fixtures required"); test.setTimeout(150_000); });
test.use({ actionTimeout: 15_000 });
for (const [locale, copy, term] of [["ru", ru, "Связаться"], ["kk", kk, "хабарласу"], ["en", en, "Follow up"]] as const) {
  test(`localized automatic task search and editor ${locale}`, async ({ page }, info) => {
    const s = await crmSession(page);
    const fixture = JSON.parse(execFileSync(process.env.E2E_PYTHON!, ["e2e/support/seed-task-search.py"], { encoding: "utf8", windowsHide: true }).trim().split("\n").at(-1)!);
    const title = copy["taskWorkspace.followUp.cancelled.title"].replace("{id}", String(fixture.appointment));
    await page.evaluate(value => localStorage.setItem("ai_smb_language", value), locale);
    await page.goto("/app/tasks");
    const search = page.getByRole("textbox", { name: copy["taskWorkspace.search"], exact: true });
    const pending = page.waitForResponse(r => {
      const u = new URL(r.url());
      return u.pathname === "/api/tasks/" && u.searchParams.get("search") === term && u.searchParams.get("locale") === locale && r.status() === 200;
    });
    await search.fill(term);
    const result = await (await pending).json();
    expect(result.results.some((row: { id: number }) => row.id === fixture.id)).toBe(true);
    const row = page.getByTestId("task-row").filter({ hasText: title });
    await expect(row).toBeVisible();
    await page.screenshot({ path: info.outputPath(`${locale}-search.png`), fullPage: true });
    await search.fill("QA016 no matching task");
    await expect(page.getByText(copy["taskWorkspace.noResults"], { exact: true })).toBeVisible();
    await search.fill("");
    await expect(row).toBeVisible();
    await search.fill(title);
    await expect(row).toBeVisible();
    await row.focus();
    await page.keyboard.press("Enter");
    const inspector = page.getByTestId("task-inspector");
    await expect(inspector.getByRole("heading", { name: title, exact: true })).toBeVisible();
    await inspector.getByRole("button", { name: copy["taskWorkspace.edit"], exact: true }).click();
    const editor = page.getByTestId("task-editor");
    const name = editor.getByLabel(copy["taskWorkspace.name"], { exact: true });
    await expect(name).toHaveValue(title);
    await expect(editor.getByRole("textbox", { name: new RegExp(`^${copy["taskWorkspace.description"]}`) })).toHaveValue(copy["taskWorkspace.followUp.cancelled.description"]);
    await editor.getByRole("combobox", { name: new RegExp(`^${copy["taskWorkspace.priority"]}`) }).click();
    await editor.getByRole("option", { name: copy["taskWorkspace.priority.urgent"], exact: true }).click();
    await editor.screenshot({ path: info.outputPath(`${locale}-editor.png`) });
    await editor.getByRole("button", { name: copy["taskWorkspace.save"], exact: true }).click();
    await expect(editor).toBeHidden();
    const saved = await s.read(`tasks/${fixture.id}`);
    expect(saved.title).toBe(fixture.title);
    expect(saved.description).toBe(fixture.description);
    expect(saved.priority).toBe("urgent");
    await inspector.getByRole("button", { name: copy["taskWorkspace.edit"], exact: true }).click();
    const customTitle = `QA016 custom title ${fixture.id}`;
    await name.fill(customTitle);
    await page.route(`**/api/tasks/${fixture.id}/update-details/`, route => route.fulfill({ status: 503, json: { detail: "Temporary test failure" } }), { times: 1 });
    await editor.getByRole("button", { name: copy["taskWorkspace.save"], exact: true }).click();
    await expect(editor.getByRole("alert")).toBeVisible();
    await expect(name).toHaveValue(customTitle);
    await editor.getByRole("button", { name: copy["taskWorkspace.save"], exact: true }).click();
    await expect(editor).toBeHidden();
    await expect(inspector.getByRole("heading", { name: customTitle, exact: true })).toBeVisible();
    await page.goto(`/app/tasks?search=${encodeURIComponent(customTitle)}`);
    await expect(page.getByTestId("task-row").filter({ hasText: customTitle })).toBeVisible();
    await page.reload();
    await expect(page.getByTestId("task-row").filter({ hasText: customTitle })).toBeVisible();
    expect((await s.read(`tasks/${fixture.id}`)).system_copy.title).toBe(false);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  });
}
