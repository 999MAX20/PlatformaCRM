import { openClinicalWorkspace } from "./clinical-card-navigation";
import { test, expect } from "@playwright/test";
import { execFileSync } from "node:child_process";
import AxeBuilder from "@axe-core/playwright";
import { ru } from "../src/lib/i18n/ru";
import { kk } from "../src/lib/i18n/kk";
import { en } from "../src/lib/i18n/en";
import { requireIsolatedEnvironment } from "./isolated-environment.mjs";

requireIsolatedEnvironment();
const dictionaries = { ru, kk, en };
let appointmentId = 0;
for (const language of ["ru", "kk", "en"] as const) {
  for (const mobile of [false, true]) {
    const id = ++appointmentId;
    test(`clinical ${language} ${mobile ? "mobile" : "desktop"}: calendar to saved draft`, async ({ page }, info) => {
      execFileSync(process.env.E2E_PYTHON!, ["e2e/clinical-runtime.py", "restore"], { env: process.env, windowsHide: true, stdio: "pipe" });
      const t = dictionaries[language];
      await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 });
      await page.addInitScript(value => localStorage.setItem("ai_smb_language", value), language);
      await page.goto("/login");
      await page.locator('input[name="email"]').fill("medical-role-doctor@example.test");
      await page.locator('input[name="password"]').fill(process.env.E2E_PASSWORD!);
      const login = page.waitForResponse(r => r.url().endsWith("/api/auth/token/") && r.request().method() === "POST");
      const me = page.waitForResponse(r => r.url().endsWith("/api/auth/me/") && r.status() === 200);
      await page.locator('form button[type="submit"]').click();
      const token = (await (await login).json()).access;
      await me;
      await expect(page).toHaveURL(/\/app\//);
      const response = await page.request.get(`${process.env.E2E_API_BASE_URL}/api/appointments/${id}/`, { headers: { Authorization: `Bearer ${token}` } });
      expect(response.status()).toBe(200);
      const appointment = await response.json();
      await page.goto(`/app/calendar?appointment=${id}&date=${appointment.start_at.slice(0, 10)}&view=day`);
      await openClinicalWorkspace(page);
      const workspace = page.getByTestId("clinical-workspace");
      await workspace.getByLabel(t["medical.clinical.number"], { exact: true }).fill(`BROWSER-${id}`);
      await workspace.getByRole("button", { name: t["medical.clinical.createRecord"], exact: true }).click();
      await workspace.getByRole("button", { name: t["medical.clinical.start"], exact: true }).click();
      const complaint = workspace.getByLabel(t["medical.clinical.complaints"], { exact: true });
      await complaint.fill(`Synthetic clinical complaint ${id}`);
      const allergies = workspace.getByLabel(t["medical.clinical.allergies"], { exact: true });
      const contraindications = workspace.getByLabel(t["medical.clinical.contraindications"], { exact: true });
      await expect(allergies).toHaveValue("");
      await expect(contraindications).toHaveValue("");
      await allergies.fill(`Synthetic allergy ${id} — оқу`);
      await contraindications.fill(`Synthetic contraindication ${id}`);
      const procedureLabel = t["medical.clinical.procedures"];
      const procedures = workspace.getByRole("textbox", { name: procedureLabel, exact: true });
      const marker = workspace.getByRole("checkbox", { name: t["medical.clinical.notApplicableFor"].replace("{field}", procedureLabel), exact: true });
      await procedures.fill("Synthetic text retained on cancelled change");
      page.once("dialog", dialog => dialog.dismiss());
      await marker.click();
      await expect(marker).not.toBeChecked();
      await expect(procedures).toHaveValue("Synthetic text retained on cancelled change");
      page.once("dialog", dialog => dialog.accept());
      await marker.check();
      const sectionReason = workspace.getByRole("textbox", { name: t["medical.clinical.notApplicableReason"].replace("{field}", procedureLabel), exact: true });
      await workspace.getByRole("button", { name: t["medical.clinical.save"], exact: true }).click();
      await expect(sectionReason).toBeFocused();
      expect(await sectionReason.evaluate((element: HTMLTextAreaElement) => element.checkValidity())).toBe(false);
      await sectionReason.fill(`Synthetic consultation only ${id}`);
      const planTab = workspace.getByRole("tab", { name: t["medical.clinical.plan"], exact: true });
      await planTab.click();
      await expect(planTab).toHaveAttribute("aria-selected", "true");
      await expect(complaint).toHaveCount(0);
      await workspace.getByRole("textbox", { name: t["medical.clinical.plan"], exact: true }).fill("Synthetic follow-up plan");
      const plan = workspace.getByTestId("clinical-plan-steps");
      const stepLabel = (number: number) => t["medical.plan.step"].replace("{number}", String(number));
      await plan.getByRole("button", { name: t["medical.plan.addStep"], exact: true }).click();
      await expect(plan.getByRole("textbox", { name: stepLabel(1), exact: true })).toBeFocused();
      await plan.getByRole("textbox", { name: stepLabel(1), exact: true }).fill("Synthetic plan A — оқу");
      await plan.getByRole("button", { name: t["medical.plan.addStep"], exact: true }).click();
      await plan.getByRole("textbox", { name: stepLabel(2), exact: true }).fill("Synthetic plan B");
      const up = plan.getByRole("button", { name: t["medical.plan.moveUpStep"].replace("{number}", "2"), exact: true });
      await up.focus(); await page.keyboard.press("Enter");
      await expect(plan.getByRole("textbox", { name: stepLabel(1), exact: true })).toHaveValue("Synthetic plan B");
      await expect(plan.getByRole("textbox", { name: stepLabel(1), exact: true })).toBeFocused();
      const remove = plan.getByRole("button", { name: t["medical.plan.removeStep"].replace("{number}", "1"), exact: true });
      page.once("dialog", dialog => dialog.dismiss()); await remove.click();
      await expect(plan.getByRole("textbox")).toHaveCount(2);
      page.once("dialog", dialog => dialog.accept()); await remove.click();
      await expect(plan.getByRole("textbox", { name: stepLabel(1), exact: true })).toHaveValue("Synthetic plan A — оқу");
      await expect(plan.getByRole("textbox", { name: stepLabel(1), exact: true })).toBeFocused();
      await plan.getByRole("button", { name: t["medical.plan.addStep"], exact: true }).click();
      await plan.getByRole("textbox", { name: stepLabel(2), exact: true }).fill("Synthetic plan C");
      const planMarker = workspace.getByRole("checkbox", { name: t["medical.clinical.notApplicableFor"].replace("{field}", t["medical.clinical.plan"]), exact: true });
      page.once("dialog", dialog => dialog.dismiss()); await planMarker.click();
      await expect(planMarker).not.toBeChecked();
      await expect(plan.getByRole("textbox")).toHaveCount(2);
      page.once("dialog", dialog => dialog.accept()); await planMarker.check();
      await expect(plan).not.toBeVisible();
      const planReason = workspace.getByLabel(t["medical.clinical.notApplicableReason"].replace("{field}", t["medical.clinical.plan"]), { exact: true });
      await planReason.fill("Synthetic no plan");
      page.once("dialog", dialog => dialog.accept()); await planMarker.uncheck();
      await expect(plan.getByRole("textbox")).toHaveCount(0);
      await plan.getByRole("button", { name: t["medical.plan.addStep"], exact: true }).click();
      await plan.getByRole("textbox", { name: stepLabel(1), exact: true }).fill("Synthetic plan A — оқу");
      await plan.getByRole("button", { name: t["medical.plan.addStep"], exact: true }).click();
      await plan.getByRole("textbox", { name: stepLabel(2), exact: true }).fill("Synthetic plan C");
      await workspace.getByRole("button", { name: t["medical.clinical.save"], exact: true }).click();
      await expect(workspace.getByText(t["common.saved"], { exact: true })).toBeVisible();
      await expect(workspace.getByRole("button", { name: t["medical.clinical.save"], exact: true })).toBeDisabled();
      await workspace.screenshot({ path: info.outputPath("clinical-plan-tab.png") });
      expect((await new AxeBuilder({ page }).include('[data-testid="clinical-workspace"]').withTags(["wcag2a", "wcag2aa"]).analyze()).violations).toEqual([]);
      await workspace.getByRole("tab", { name: t["medical.overview.title"], exact: true }).click();
      await workspace.getByTestId("clinical-overview").getByRole("button", { name: t["medical.clinical.plan"], exact: true }).click();
      await expect(planTab).toBeFocused();
      await planTab.scrollIntoViewIfNeeded();
      await workspace.screenshot({ path: info.outputPath("clinical-plan-tab-header.png") });
      await workspace.getByRole("tab", { name: t["medical.clinical.note"], exact: true }).click();
      await expect(complaint).toHaveValue(`Synthetic clinical complaint ${id}`);
      await workspace.screenshot({ path: info.outputPath("clinical-draft.png") });
      await plan.evaluate(element => element.scrollIntoView({ block: "center" }));
      await plan.screenshot({ path: info.outputPath("clinical-plan-steps.png") });
      for (const [field, name] of [[allergies, "allergies"], [contraindications, "contraindications"]] as const) {
        const container = field.locator("..");
        await container.evaluate(element => element.scrollIntoView({ block: "center" }));
        await container.screenshot({ path: info.outputPath(`clinical-${name}.png`) });
      }
      await sectionReason.locator("../..").evaluate(element => element.scrollIntoView({ block: "center" }));
      await sectionReason.locator("../..").screenshot({ path: info.outputPath("clinical-not-applicable.png") });
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
      expect((await new AxeBuilder({ page }).include('[data-testid="clinical-workspace"]').withTags(["wcag2a", "wcag2aa"]).analyze()).violations).toEqual([]);
      await page.keyboard.press("Escape");
      await expect(workspace).not.toBeVisible();
      await expect(page.locator("[data-calendar-day]:focus")).toHaveCount(1);
      await openClinicalWorkspace(page, true);
      await expect(complaint).toHaveValue(`Synthetic clinical complaint ${id}`);
      await expect(allergies).toHaveValue(`Synthetic allergy ${id} — оқу`);
      await expect(contraindications).toHaveValue(`Synthetic contraindication ${id}`);
      await expect(marker).toBeChecked();
      await expect(sectionReason).toHaveValue(`Synthetic consultation only ${id}`);
      await expect(plan.getByRole("textbox", { name: stepLabel(1), exact: true })).toHaveValue("Synthetic plan A — оқу");
      await expect(plan.getByRole("textbox", { name: stepLabel(2), exact: true })).toHaveValue("Synthetic plan C");
      await complaint.fill(`Unsaved while reading history ${id}`);
      await workspace.getByRole("tab", { name: t["medical.clinical.history"], exact: true }).click();
      const history = workspace.getByTestId("clinical-history");
      await history.locator("button[aria-pressed]").first().click();
      const reader = workspace.getByTestId("clinical-version");
      await expect(reader).toContainText(`Synthetic clinical complaint ${id}`);
      await expect(reader).toContainText(`Synthetic allergy ${id} — оқу`);
      await expect(reader).toContainText(`Synthetic contraindication ${id}`);
      await expect(reader).toContainText(`${t["medical.clinical.notApplicable"]}: Synthetic consultation only ${id}`);
      await expect(reader).toContainText("Synthetic clinician");
      await expect(reader.getByTestId("clinical-plan-history").getByRole("listitem")).toHaveText(["Synthetic plan A — оқу", "Synthetic plan C"]);
      await reader.getByTestId("clinical-plan-history").screenshot({ path: info.outputPath("clinical-plan-history.png") });
      await expect(reader.getByRole("textbox")).toHaveCount(0);
      const revisions = workspace.getByTestId("clinical-revisions");
      await revisions.getByRole("button").filter({ hasText: new RegExp(`^${t["medical.clinical.revision"]} 1`) }).click();
      await expect(reader).not.toContainText(`Synthetic clinical complaint ${id}`);
      await expect(reader).not.toContainText(`Synthetic allergy ${id} — оқу`);
      await expect(reader).not.toContainText(`Synthetic consultation only ${id}`);
      await expect(reader.getByTestId("clinical-plan-history")).toHaveCount(0);
      await expect(reader).toContainText(t["medical.clinical.notRecorded"]);
      await workspace.screenshot({ path: info.outputPath("clinical-history.png") });
      expect((await new AxeBuilder({ page }).include('[data-testid="clinical-workspace"]').withTags(["wcag2a", "wcag2aa"]).analyze()).violations).toEqual([]);
      await workspace.getByRole("tab", { name: t["medical.clinical.note"], exact: true }).click();
      await expect(complaint).toHaveValue(`Unsaved while reading history ${id}`);
      await workspace.getByRole("button", { name: t["medical.clinical.save"], exact: true }).click();
      await expect(workspace.getByText(t["common.saved"], { exact: true })).toBeVisible();
      await workspace.getByRole("tab", { name: t["medical.clinical.history"], exact: true }).click();
      await history.locator("button[aria-pressed]").first().click();
      await expect(reader).toContainText(`${t["medical.clinical.revision"]} 1`);
      await revisions.getByRole("button").filter({ hasText: new RegExp(`^${t["medical.clinical.revision"]} 3`) }).click();
      await expect(reader).toContainText(`Unsaved while reading history ${id}`);
      expect(await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))).not.toContain("Synthetic clinical complaint");
      await workspace.getByRole("tab", { name: t["medical.clinical.note"], exact: true }).click();
      await complaint.fill(`Unsaved close ${id}`);
      await planTab.click();
      await page.keyboard.press("Escape");
      const unsaved = page.getByTestId("clinical-unsaved");
      await expect(unsaved).toBeVisible();
      await unsaved.screenshot({ path: info.outputPath("clinical-unsaved.png") });
      expect((await new AxeBuilder({ page }).include('[data-testid="clinical-unsaved"]').withTags(["wcag2a", "wcag2aa"]).analyze()).violations).toEqual([]);
      await unsaved.getByRole("button", { name: t["medical.clinical.continueEditing"], exact: true }).click();
      await expect(unsaved).not.toBeVisible();
      await expect(planTab).toHaveAttribute("aria-selected", "true");
      await workspace.getByRole("tab", { name: t["medical.clinical.note"], exact: true }).click();
      await expect(complaint).toHaveValue(`Unsaved close ${id}`);
      await page.keyboard.press("Escape");
      await unsaved.getByRole("button", { name: t["medical.clinical.leaveUnsaved"], exact: true }).click();
      await expect(workspace).not.toBeVisible();
      await expect(page.locator("[data-calendar-day]:focus")).toHaveCount(1);
      await openClinicalWorkspace(page, true);
      await expect(complaint).toHaveValue(`Unsaved while reading history ${id}`);
      await complaint.fill(`Saved on close ${id}`);
      await page.keyboard.press("Escape");
      await unsaved.getByRole("button", { name: t["medical.clinical.saveClose"], exact: true }).click();
      await expect(workspace).not.toBeVisible();
      await openClinicalWorkspace(page, true);
      await expect(complaint).toHaveValue(`Saved on close ${id}`);

    });
  }
}
